#!/usr/bin/env python3
"""Refresh this project's independently locked Cargo source and audit manifests."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
SECTION = "# Generated by tools/sync_vendor.py\n"
CONFIG = """[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"

[net]
offline = true
"""
PRUNED = ("tests", "benches", "examples", "docs", "sqlcipher", "test-macros", "test-data")
INCLUDES = re.compile(r'\binclude(?:_str|_bytes)?!\s*\(\s*"([^"]+)"')
UNSUPPORTED_UNIX = (
    "aix", "cygwin", "haiku", "hurd", "newlib", "nto", "nuttx", "redox", "solarish",
)


def remove(path: Path) -> None:
    if path.is_dir():
        shutil.rmtree(path)
    elif path.exists():
        path.unlink()


def prune(package: Path, name: str) -> None:
    required = compilation_inputs(package)
    for item in PRUNED:
        path = package / item
        if any(source.is_relative_to(path) for source in required):
            trim_tree(path, required)
        else:
            remove(path)
    prune_platforms(package, name, server=False)


def prune_platforms(package: Path, name: str, *, server: bool) -> None:
    excluded = {"wasi", "wasip2", "wit-bindgen", "r-efi"}
    if server:
        excluded.update(("windows-sys", "windows-link", "anstyle-wincon", "winapi-util"))
    if name in excluded:
        for item in ("src", "wit", "bindings"):
            remove(package / item)
    if name == "libc":
        prune_libc(package / "src", server=server)
    if name == "blake3":
        for assembly in (package / "c").glob("*_windows_gnu.S"):
            remove(assembly)
        if server:
            for assembly in (package / "c").glob("*_windows_msvc.asm"):
                remove(assembly)
    for path in package.glob("lib/*"):
        if path.name.startswith(("i686_", "i586_")) or path.name.endswith(("_gnullvm", "_gnu")):
            remove(path)


def prune_libc(source: Path, *, server: bool) -> None:
    for system in UNSUPPORTED_UNIX:
        remove(source / "unix" / system)
    remove(source / "wasi")
    remove(source / "new" / "wasi")
    bsd = source / "unix" / "bsd"
    for system in ("freebsdlike", "netbsdlike"):
        remove(bsd / system)
    if server:
        remove(bsd / "apple")
    else:
        remove(bsd / "apple" / "b64" / "x86_64")
    for parent in (source / "unix" / "linux_like", bsd / "apple"):
        for path in sorted(parent.rglob("b32"), reverse=True):
            remove(path)
    for path in source.glob("unix/linux_like/linux/*/b64/x86_64/x32.rs"):
        remove(path)


def compilation_inputs(package: Path) -> set[Path]:
    inputs = set()
    for rust in package.rglob("*.rs"):
        if rust.relative_to(package).parts[0] in PRUNED:
            continue
        for match in INCLUDES.finditer(rust.read_text(encoding="utf-8", errors="replace")):
            source = (rust.parent / match[1]).resolve()
            if source.is_relative_to(package) and source.relative_to(package).parts[0] in PRUNED:
                inputs.add(source)
    return inputs


def trim_tree(path: Path, required: set[Path]) -> None:
    if not path.is_dir():
        return
    for item in sorted(path.rglob("*"), key=lambda item: len(item.parts), reverse=True):
        if item.is_dir():
            if not any(item.iterdir()):
                item.rmdir()
        elif item not in required:
            item.unlink()


def checksums(vendor: Path) -> str:
    rows = []
    for path in sorted(p for p in vendor.rglob("*") if p.is_file()):
        with path.open("rb") as source:
            digest = hashlib.file_digest(source, "sha256").hexdigest()
        rows.append(f"{digest}  vendor/{path.relative_to(vendor).as_posix()}")
    return "\n".join(rows) + "\n"


def prepare(vendor: Path) -> str:
    rows = ["# Upstream registry packages from Cargo.lock."]
    for package in sorted(vendor.iterdir()):
        checksum = package / ".cargo-checksum.json"
        catalog = json.loads(checksum.read_text(encoding="utf-8"))
        manifest = tomllib.loads((package / "Cargo.toml").read_text(encoding="utf-8"))["package"]
        prune(package, manifest["name"])
        checksum.write_text(json.dumps({"package": catalog["package"], "files": {}}, separators=(",", ":")) + "\n")
        rows.append("\n[[package]]")
        for key, value in (
            ("name", manifest["name"]), ("version", manifest["version"]),
            ("license", manifest.get("license") or manifest.get("license-file") or ""),
            ("sha256", catalog["package"]),
        ):
            rows.append(f"{key} = {json.dumps(value, ensure_ascii=False)}")
    return "\n".join(rows) + "\n"


def sync() -> None:
    config = ROOT / ".cargo" / "config.toml"
    env = dict(os.environ, CARGO_NET_OFFLINE="false")
    with tempfile.TemporaryDirectory(prefix=".zxs-vendor-", dir=ROOT) as temporary:
        stage = Path(temporary)
        vendor = stage / "vendor"
        subprocess.run(["cargo", "vendor", "--locked", "--versioned-dirs", str(vendor)],
                       cwd=ROOT, env=env, check=True, stdout=subprocess.DEVNULL)
        inventory = prepare(vendor)
        sums = checksums(vendor)
        config_text = config.read_text(encoding="utf-8").split(SECTION, 1)[0].rstrip()
        for name, data in (("VENDOR.toml", inventory), ("VENDOR.sha256", sums),
                           ("config.toml", config_text + "\n\n" + SECTION + CONFIG)):
            (stage / name).write_text(data, encoding="utf-8")
        current = ROOT / "vendor"
        previous = stage / "previous"
        if current.exists():
            current.rename(previous)
        try:
            vendor.rename(current)
        except OSError:
            if previous.exists():
                previous.rename(current)
            raise
        for name in ("VENDOR.toml", "VENDOR.sha256"):
            (stage / name).replace(ROOT / name)
        (stage / "config.toml").replace(config)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify vendored files against VENDOR.sha256")
    if parser.parse_args().check:
        expected = (ROOT / "VENDOR.sha256").read_text(encoding="utf-8")
        if checksums(ROOT / "vendor") != expected:
            parser.exit(1, "vendor checksum or contents changed\n")
        print("vendor checksums verified")
    else:
        sync()


if __name__ == "__main__":
    main()
